/** B-V → RGB tint (approx blackbody-ish ramp, visual only). */
export function bvToRGB(bv: number): [number, number, number] {
  const b = Math.max(-0.3, Math.min(2.0, bv));
  if (b < 0.3) return [0.75 + b * 0.5, 0.82 + b * 0.3, 1.0];
  if (b < 1.0) return [1.0, 0.95 - (b - 0.3) * 0.25, 0.85 - (b - 0.3) * 0.3];
  return [1.0, 0.78 - Math.min(0.2, (b - 1.0) * 0.2), 0.64 - Math.min(0.2, (b - 1.0) * 0.2)];
}
